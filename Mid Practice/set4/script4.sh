#!/bin/bash

# `for` loop in Bash:
# - A `for` loop repeats a block of commands for each item in a list.
# - It is useful when you know how many times you want to repeat something.
#
# Syntax:
# for variable in list
# do
#     commands
# done
#
# Example:
# for name in Alice Bob Charlie
# do
#     echo "Hello, $name"
# done
#
# Output:
# Hello, Alice
# Hello, Bob
# Hello, Charlie




