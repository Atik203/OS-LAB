# Difference between `cp` and `mv`:
#
# `cp` copies a file or directory to a new location.
# The original file stays in place.
# Example:
# cp file.txt backup.txt
# This creates a duplicate named `backup.txt`.
#
# `mv` moves a file or directory to a new location.
# It can also be used to rename a file.
# Example:
# mv file.txt documents/
# This moves `file.txt` into the `documents` folder.
# Example rename:
# mv oldname.txt newname.txt
#
# In short:
# `cp` = make a copy
# `mv` = move or rename



