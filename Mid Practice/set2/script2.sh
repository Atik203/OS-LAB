#! /bin/bash

# `>` redirects output to a file and overwrites the file if it already exists.
# Example:
# echo "First line" > output.txt
# If `output.txt` already has content, it will be replaced by "First line".

# `>>` redirects output to a file and appends to the end of the file.
# Example:
# echo "Second line" >> output.txt
# If `output.txt` already has content, this adds "Second line" after it.

# Example commands together:
# echo "Hello" > sample.txt
# echo "World" >> sample.txt
# After these commands, sample.txt will contain:
# Hello
# World
