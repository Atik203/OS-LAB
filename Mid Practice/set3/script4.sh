# Absolute path:
# - A full path that starts from the root directory `/`.
# - It always points to the same location no matter where you are.
# Example:
# /home/atik/oslab/file.txt

# Relative path:
# - A path that is based on the current directory.
# - It changes depending on where you are when you run the command.
# Example:
# file.txt
# ./docs/file.txt
# ../file.txt

# Example:
# If you are in `/home/atik/oslab`, then `./file.txt` means
# `/home/atik/oslab/file.txt`, but the absolute path is still
# `/home/atik/oslab/file.txt`.



