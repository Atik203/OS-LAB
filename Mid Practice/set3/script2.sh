#! /bin/bash

# `ls | grep txt` means:
# 1. `ls` lists the files and folders in the current directory.
# 2. `|` sends the output of `ls` to the next command.
# 3. `grep txt` filters that output and shows only lines containing `txt`.
#
# Example result:
# If the directory has `notes.txt`, `image.png`, and `report.txt`,
# the command will display only `notes.txt` and `report.txt`.


